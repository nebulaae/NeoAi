/**
 * Сигнал «авторизация внутри WebApp завершена».
 *
 * Проблема, которую решает: при первом открытии мини-аппа провайдер
 * (TelegramProvider/MaxProvider) асинхронно получает initData и дергает
 * /api/auth/tma. Это может занять несколько секунд. AuthGuard раньше
 * сдавался по таймеру (1.5с) и показывал экран входа — а через мгновение
 * приходил успешный логин. Отсюда «мигание» экрана входа на первом запуске.
 *
 * Теперь провайдеры явно сообщают, что попытка тихого входа завершена
 * (успех ИЛИ исчерпаны ретраи), и только тогда AuthGuard принимает решение
 * показывать ли NotAuthorized.
 */

let settled = false;
const listeners = new Set<() => void>();

/** Вызывается провайдером, когда тихий вход завершён (успех или окончательный провал). */
export function markAuthSettled(): void {
  if (settled) return;
  settled = true;
  listeners.forEach((l) => {
    try {
      l();
    } catch {}
  });
}

export function isAuthSettled(): boolean {
  return settled;
}

/** Подписка на завершение тихого входа. Возвращает функцию отписки. */
export function onAuthSettled(cb: () => void): () => void {
  if (settled) {
    cb();
    return () => {};
  }
  listeners.add(cb);
  return () => listeners.delete(cb);
}

/* ────────────────────────────────────────────────────────────────────────────
 * Протухшая сессия
 * ──────────────────────────────────────────────────────────────────────────── */

const invalidationListeners = new Set<() => void>();

/**
 * Сигнал «сохранённая сессия оказалась невалидной» — бекенд ответил 401.
 *
 * Проблема, которую решает (баг «в шапке 0 токенов до перелогина»):
 * при старте AuthProvider достаёт пользователя из JWT в localStorage, поэтому
 * интерфейс выглядит авторизованным ещё до первого запроса. Провайдер тихого
 * входа при этом выходит сразу — раз токен есть, входить не нужно. Если токен
 * протух, первый же /api/user отдаёт 401, перехватчик стирает сессию — и
 * заново никто не логинится. Баланс так и остаётся нулевым, пока пользователь
 * вручную не выйдет и не зайдёт снова.
 *
 * Теперь перехватчик шлёт этот сигнал, а провайдеры повторяют тихий вход.
 */
export function notifyAuthInvalidated(): void {
  invalidationListeners.forEach((l) => {
    try {
      l();
    } catch {}
  });
}

/** Подписка на протухание сессии. Возвращает функцию отписки. */
export function onAuthInvalidated(cb: () => void): () => void {
  invalidationListeners.add(cb);
  return () => invalidationListeners.delete(cb);
}
